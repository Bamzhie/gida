package ng.gida.media;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.NoSuchFileException;
import java.nio.file.Path;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

/**
 * Filesystem-backed {@link ObjectStorage} rooted at {@code GIDA_MEDIA_DIR}
 * (default {@code ./data/media}). The directory is resolved and created at
 * startup. Keys are relative paths under the root; absolute keys, keys with
 * {@code ..} segments and Windows drive paths are refused so a key can never
 * escape the root. The adapter derives serving content types from the key's
 * validated extension (see {@link MediaTypes}) — keys are generated by
 * {@code MediaStorageService}, which only ever pairs a whitelisted extension
 * with the matching content type, so the {@code contentType} argument of
 * {@link #put(String, byte[], String)} needs no separate metadata record.
 */
@Component
public class LocalObjectStorage implements ObjectStorage {

    private final Path root;

    public LocalObjectStorage(@Value("${GIDA_MEDIA_DIR:./data/media}") String directory) {
        this.root = Path.of(directory).toAbsolutePath().normalize();
        try {
            Files.createDirectories(root);
        } catch (IOException e) {
            throw new IllegalStateException("Cannot create the media directory " + root, e);
        }
    }

    @Override
    public String put(String key, byte[] content, String contentType) {
        Path file = location(key);
        try {
            Files.createDirectories(file.getParent());
            Files.write(file, content);
        } catch (IOException e) {
            throw new UncheckedStorageException("Cannot write the stored object " + key, e);
        }
        return key;
    }

    @Override
    public byte[] get(String key) {
        Path file = location(key);
        if (!Files.isRegularFile(file)) {
            throw new UncheckedStorageException("No stored object " + key, new NoSuchFileException(key));
        }
        try {
            return Files.readAllBytes(file);
        } catch (IOException e) {
            throw new UncheckedStorageException("Cannot read the stored object " + key, e);
        }
    }

    @Override
    public void delete(String key) {
        try {
            Files.deleteIfExists(location(key));
        } catch (IOException e) {
            throw new UncheckedStorageException("Cannot delete the stored object " + key, e);
        }
    }

    @Override
    public boolean exists(String key) {
        return Files.isRegularFile(location(key));
    }

    Path root() {
        return root;
    }

    private Path location(String key) {
        if (key == null || key.isBlank() || key.contains("..")
                || Path.of(key).isAbsolute() || key.matches("(?i)^[A-Za-z]:.*")) {
            throw new IllegalArgumentException("Illegal storage key: " + key);
        }
        Path resolved = root.resolve(key).normalize();
        if (!resolved.startsWith(root)) {
            throw new IllegalArgumentException("Illegal storage key: " + key);
        }
        return resolved;
    }
}
